    /** 取单页内容；key 非法返回 null */
    public static function get($key)
    {
        $key = (string)$key;
        if (!array_key_exists($key, self::all())) {
            return null;
        }
        $method = 'content' . str_replace(' ', '', ucwords(str_replace('-', ' ', $key)));
        return method_exists(self::class, $method) ? self::$method() : null;
    }

